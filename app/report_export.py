"""Report export utilities for NEARMISS dashboard.
Generates structured Markdown and HTML summary reports for plant safety officers.
"""

from datetime import datetime
import pandas as pd


def generate_safety_audit_report(
    summary_stats: dict,
    high_risk_units: pd.DataFrame,
    active_filters: dict,
) -> str:
    """Generate an executive industrial safety audit report in Markdown format."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    high_risk_table = "No units currently exceed the critical alert threshold."
    if not high_risk_units.empty:
        cols_to_show = [c for c in ["facility", "unit_id", "equipment_type", "predicted_risk_pct", "anomaly_flag", "vibration_rms_mms", "pm_overdue_days"] if c in high_risk_units.columns]
        high_risk_table = high_risk_units[cols_to_show].head(15).to_markdown(index=False)

    report = f"""# INDUSTRIAL SAFETY INTELLIGENCE AUDIT REPORT
**Generated:** {now_str}
**System:** NEARMISS (Predictive Industrial Safety Intelligence)
**Classification:** Operational Safety Decision Support

---

## 1. Executive Summary
This report summarizes predictive risk assessments generated by the NEARMISS intelligence system.
Warning signals are computed using historical near-miss frequency, maintenance backlog, ISO 10816 vibration guidelines, and shift human factors.

> **DECISION SUPPORT DISCLAIMER:**
> Risk probabilities provided in this report are predictive estimations intended for risk prioritization, proactive inspection, and maintenance scheduling. They do not represent a certainty that an incident will or will not occur.

---

## 2. Active Scope & Filters
- **Facility Filter:** {active_filters.get('facility', 'All Facilities')}
- **Equipment Filter:** {active_filters.get('equipment', 'All Equipment')}
- **Date Window:** {active_filters.get('start_date', 'N/A')} to {active_filters.get('end_date', 'N/A')}
- **Total Observations Analyzed:** {summary_stats.get('total_observations', 0):,}

---

## 3. Fleet Safety KPIs
- **Total Historical Incidents:** {summary_stats.get('total_incidents', 0):,}
- **Total Near-Miss Hazards Logged:** {summary_stats.get('total_near_misses', 0):,}
- **Fleet Heinrich Ratio (Near-Misses per Incident):** {summary_stats.get('heinrich_ratio', 0.0):.1f} : 1
- **Average 7-Day Predicted Incident Risk:** {summary_stats.get('avg_predicted_risk', 0.0):.2f}%
- **Operational Anomaly Detection Rate:** {summary_stats.get('anomaly_rate', 0.0):.2f}%
- **Total Critical / High-Risk Equipment Units:** {summary_stats.get('high_risk_count', 0)}

---

## 4. Prioritized High-Risk Equipment Units (Action Required)
The following industrial assets have demonstrated significant hazard accumulation (calibrated risk >= 35% or multi-sensor anomaly flag):

{high_risk_table}

---

## 5. Recommended Preventive Action Protocols
1. **Units with Calibrated Risk >= 50%**:
   - Issue mandatory safety stand-down before next shift change.
   - Dispatch mechanical technician for ISO 10816 vibration spectrum check.
   - Expedite overdue preventive maintenance tickets.
2. **Units with High Near-Miss Clustering (>= 2 events in 7 days)**:
   - Perform ergonomic and job-safety analysis (JSA) on operating procedures.
   - Inspect physical guards and pressure relief interlocks.
3. **Units with Operational Anomalies**:
   - Inspect thermal dissipation and lubrication condition.

*NEARMISS Intelligence Engine v1.0.0 — Safety First, Always.*
"""
    return report
